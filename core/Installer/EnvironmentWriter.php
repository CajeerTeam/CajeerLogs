<?php
declare(strict_types=1);
namespace Cajeer\Logs\Installer;

use Cajeer\Logs\Config\Environment;
use Cajeer\Logs\Database\DatabaseException;
use Cajeer\Logs\Kernel\Application;

final class EnvironmentWriter
{
    public function __construct(private readonly Application $app) {}

    public function write(): void
    {
        $path = $this->app->basePath('.env');
        if (is_link($path)) { throw new DatabaseException('Refusing to replace a symlinked .env file.'); }
        $values = is_file($path) ? Environment::load($path) : Environment::load($this->app->basePath('.env.example'));
        if (!is_file($path)) { $values['APP_ENV'] = 'production'; $values['APP_DEBUG'] = 'false'; }
        // Preserve effective runtime settings when installing from environment-only configuration.
        foreach (['APP_NAME','APP_ENV','APP_DEBUG','APP_URL','APP_LOCALE','APP_TIMEZONE','APP_MAX_BODY_BYTES','API_PREFIX','API_RATE_LIMIT_PER_MINUTE','PROMETHEUS_ENABLED','PROMETHEUS_PATH','OPENAPI_PATH','INGEST_REQUIRE_HMAC'] as $key) {
            if (getenv($key) !== false || isset($_ENV[$key])) { $values[$key] = env_raw($key); }
        }
        $keys = ['DB_CONNECTION'=>'default','DB_HOST'=>'host','DB_PORT'=>'port','DB_DATABASE'=>'database','DB_USERNAME'=>'username','DB_PASSWORD'=>'password','DB_SCHEMA'=>'schema','DB_SSLMODE'=>'sslmode','DB_SSLROOTCERT'=>'sslrootcert','DB_CONNECT_TIMEOUT'=>'connect_timeout','DB_STATEMENT_TIMEOUT_MS'=>'statement_timeout_ms','DB_LOCK_TIMEOUT_MS'=>'lock_timeout_ms'];
        foreach ($keys as $env => $key) { $values[$env] = (string) $this->app->config()->get('database.' . $key); }
        foreach (['SECURITY_HMAC_SECRET','SECURITY_TOKEN_PEPPER','SECURITY_PRIVACY_HASH_PEPPER','WEBHOOK_SIGNING_SECRET'] as $key) {
            $external = getenv($key);
            $value = $external !== false ? $external : (string) ($_ENV[$key] ?? $values[$key] ?? '');
            $values[$key] = strlen($value) < 32 || str_starts_with($value, 'change_me') ? bin2hex(random_bytes(32)) : $value;
            if (($external !== false || isset($_ENV[$key])) && $value !== $values[$key]) { throw new DatabaseException('Remove placeholder external secret before installation: ' . $key); }
        }
        // Preserve existing keys; never persist the administrator password.
        unset($values['CAJEER_ADMIN_PASSWORD']);
        $body = "# CajeerLogs configuration; generated by CLI installer. Keep private.\n";
        foreach ($values as $key => $value) {
            $body .= $key . '="' . strtr($value, ['\\'=>'\\\\','"'=>'\\"',"\n"=>'\\n',"\r"=>'\\r',"\t"=>'\\t']) . "\"\n";
        }
        $temp = tempnam(dirname($path), '.env-install-');
        if ($temp === false) { throw new DatabaseException('Cannot create temporary environment file.'); }
        if (realpath(dirname($temp)) !== realpath(dirname($path))) { unlink($temp); throw new DatabaseException('Temporary environment file must be on the same filesystem.'); }
        try {
            if (!chmod($temp, 0600) || file_put_contents($temp, $body, LOCK_EX) !== strlen($body) || !rename($temp, $path)) { throw new DatabaseException('Cannot atomically write .env.'); }
        } finally { if (is_file($temp)) { unlink($temp); } }
    }
}
